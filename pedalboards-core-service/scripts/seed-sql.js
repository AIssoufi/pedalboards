import { toPluginId } from '../src/utils/plugin-id.js';
import { PLUGIN_COLUMNS } from './constants.js';

/**
 * Writes a value as an SQL literal: objects and arrays become JSON text, booleans 1 or 0.
 *
 * @param {unknown} value - Field of a plugin.
 * @returns {string} The SQL literal.
 */
export const toSqlLiteral = value => {
	if (value === undefined || value === null) {
		return 'NULL';
	}
	if (typeof value === 'boolean') {
		return value ? '1' : '0';
	}
	if (typeof value === 'number') {
		return String(value);
	}
	const text = typeof value === 'object' ? JSON.stringify(value) : String(value);
	return `'${text.replaceAll("'", "''")}'`;
};

/**
 * Builds the migration that inserts the seed plugins, one INSERT statement per plugin.
 *
 * @param {Object[]} plugins - Plugins of data/plugins.json.
 * @returns {string} The SQL of the migration.
 * @throws {Error} When a plugin has no name to make its id from, or two plugins get the same id.
 */
export const buildSeedSql = plugins => {
	const ids = plugins.map(plugin => toPluginId(String(plugin.name ?? '')));
	const hasEmptyId = ids.includes('');
	if (hasEmptyId) {
		throw new Error('A plugin has no name to make its id from');
	}
	const isRepeatedId = (id, index) => ids.indexOf(id) !== index;
	const duplicateId = ids.find(isRepeatedId);
	if (duplicateId !== undefined) {
		throw new Error(`Two plugins get the id "${duplicateId}"`);
	}

	const statements = plugins.map((plugin, index) => {
		const values = PLUGIN_COLUMNS.map(column => toSqlLiteral(column === 'id' ? ids[index] : plugin[column]));
		return `INSERT INTO plugins (${PLUGIN_COLUMNS.join(', ')}) VALUES (${values.join(', ')});`;
	});

	return [
		'-- Generated by scripts/generate-seed-migration.js from data/plugins.json: do not edit',
		...statements,
		''
	].join('\n');
};
